//! Executable domain invariants and validation rules for the Swap Engine.
//!
//! Enforces:
//! 1. Reservation vs Inventory balances (`ReservationExceedsInventory`)
//! 2. Legal state machine transitions (`IllegalStateTransition`)
//! 3. Immutability of terminal order states (`TerminalOrderTransition`)
//! 4. Cumulative fill bounds (`FillsExceedOrderAmount`)
//! 5. Value conservation across input, output, and fees (`ValueConservationViolated`)
//! 6. Non-negative quantities and arithmetic safety (`ArithmeticSafetyViolated`)

use bigdecimal::{BigDecimal, Zero};
use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::fmt;
use uuid::Uuid;

/// Asset identifier (e.g., "USDC", "XLM", "BTC", "ETH").
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct Asset(pub String);

impl From<&str> for Asset {
    fn from(s: &str) -> Self {
        Self(s.to_string())
    }
}

impl fmt::Display for Asset {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
    }
}

/// Side of the swap order.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum OrderSide {
    Buy,
    Sell,
}

/// Lifecycle states for a swap order.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum SwapOrderStatus {
    Pending,
    Reserved,
    PartiallyFilled,
    Filled,
    Cancelled,
    Expired,
    Failed,
}

impl SwapOrderStatus {
    /// True if the order has reached an immutable terminal state.
    pub fn is_terminal(&self) -> bool {
        matches!(
            self,
            SwapOrderStatus::Filled
                | SwapOrderStatus::Cancelled
                | SwapOrderStatus::Expired
                | SwapOrderStatus::Failed
        )
    }

    /// True if the transition from `self` to `next` is allowed by the domain state machine.
    pub fn can_transition_to(&self, next: SwapOrderStatus) -> bool {
        if self == &next {
            return true;
        }
        if self.is_terminal() {
            return false;
        }
        match self {
            SwapOrderStatus::Pending => matches!(
                next,
                SwapOrderStatus::Reserved | SwapOrderStatus::Cancelled | SwapOrderStatus::Failed
            ),
            SwapOrderStatus::Reserved => matches!(
                next,
                SwapOrderStatus::PartiallyFilled
                    | SwapOrderStatus::Filled
                    | SwapOrderStatus::Cancelled
                    | SwapOrderStatus::Expired
                    | SwapOrderStatus::Failed
            ),
            SwapOrderStatus::PartiallyFilled => matches!(
                next,
                SwapOrderStatus::PartiallyFilled
                    | SwapOrderStatus::Filled
                    | SwapOrderStatus::Cancelled
                    | SwapOrderStatus::Expired
                    | SwapOrderStatus::Failed
            ),
            _ => false,
        }
    }
}

/// Request for a swap price quote.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct QuoteRequest {
    pub id: Uuid,
    pub tenant_id: Option<Uuid>,
    pub source_asset: String,
    pub target_asset: String,
    pub amount: BigDecimal,
    pub side: OrderSide,
    pub min_output_amount: Option<BigDecimal>,
    pub max_slippage_bps: u32,
    pub deadline: DateTime<Utc>,
}

/// Binding swap quote generated by an oracle / liquidity provider.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Quote {
    pub id: Uuid,
    pub request_id: Uuid,
    pub source_asset: String,
    pub target_asset: String,
    pub input_amount: BigDecimal,
    pub output_amount: BigDecimal,
    pub fee_amount: BigDecimal,
    pub spread_bps: u32,
    pub expires_at: DateTime<Utc>,
    pub signature: String,
}

/// Record of an executed swap fill (full or partial).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Fill {
    pub fill_id: Uuid,
    pub order_id: Uuid,
    pub amount_in: BigDecimal,
    pub amount_out: BigDecimal,
    pub fee_paid: BigDecimal,
    pub executed_at: DateTime<Utc>,
}

/// Active or historical swap order.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SwapOrder {
    pub id: Uuid,
    pub quote_id: Uuid,
    pub tenant_id: Option<Uuid>,
    pub status: SwapOrderStatus,
    pub source_asset: String,
    pub target_asset: String,
    pub requested_amount: BigDecimal,
    pub filled_amount: BigDecimal,
    pub reserved_amount: BigDecimal,
    pub fills: Vec<Fill>,
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
    pub expires_at: DateTime<Utc>,
}

/// Inventory balance and reservations for an asset.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Inventory {
    pub asset: String,
    pub total_amount: BigDecimal,
    pub reserved_amount: BigDecimal,
}

impl Inventory {
    pub fn new(asset: impl Into<String>, total: BigDecimal) -> Self {
        Self {
            asset: asset.into(),
            total_amount: total,
            reserved_amount: BigDecimal::zero(),
        }
    }

    pub fn available_amount(&self) -> BigDecimal {
        &self.total_amount - &self.reserved_amount
    }
}

/// Complete in-memory state of the swap engine.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct SwapEngineState {
    pub inventories: HashMap<String, Inventory>,
    pub orders: HashMap<Uuid, SwapOrder>,
}

/// Formal violation of swap engine invariants.
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum SwapInvariantViolation {
    #[error("Reservation exceeds inventory for asset {asset}: reserved {reserved} > total {total} (available: {available})")]
    ReservationExceedsInventory {
        asset: String,
        reserved: BigDecimal,
        total: BigDecimal,
        available: BigDecimal,
    },

    #[error("Illegal state transition for order {order_id}: attempted {from:?} -> {to:?}")]
    IllegalStateTransition {
        order_id: Uuid,
        from: SwapOrderStatus,
        to: SwapOrderStatus,
    },

    #[error("Attempted transition from terminal status {terminal_status:?} for order {order_id}: {attempted_action}")]
    TerminalOrderTransition {
        order_id: Uuid,
        terminal_status: SwapOrderStatus,
        attempted_action: String,
    },

    #[error(
        "Fills exceed order amount for order {order_id}: filled {filled} > requested {requested}"
    )]
    FillsExceedOrderAmount {
        order_id: Uuid,
        filled: BigDecimal,
        requested: BigDecimal,
    },

    #[error("Value conservation violated for order {order_id}: input={input}, output={output}, fee={fee}, reason={reason}")]
    ValueConservationViolated {
        order_id: Uuid,
        input: BigDecimal,
        output: BigDecimal,
        fee: BigDecimal,
        reason: String,
    },

    #[error("Arithmetic safety violated: {reason}")]
    ArithmeticSafetyViolated { reason: String },
}

/// Validates all core invariants over the swap engine state:
///
/// 1. **Inventory Balance**: For all assets: `0 <= reserved_amount <= total_amount`.
/// 2. **Reservation Conservation**: The sum of `reserved_amount` in active orders for asset `A`
///    does not exceed `inventory.reserved_amount` for `A`.
/// 3. **Order State Consistency**:
///    - `requested_amount > 0`
///    - `0 <= filled_amount <= requested_amount` (otherwise `FillsExceedOrderAmount`)
///    - `sum(fills.amount_in) == filled_amount`
///    - If `status.is_terminal()`: `reserved_amount == 0` (otherwise `TerminalOrderTransition`)
///    - If `status == Filled`: `filled_amount == requested_amount`
///    - If `status == PartiallyFilled`: `0 < filled_amount < requested_amount`
///    - If `status == Pending`: `filled_amount == 0`
/// 4. **Value Conservation**:
///    - All fill inputs, outputs, and fees must be strictly non-negative.
///    - `amount_in > 0`, `amount_out > 0`.
pub fn check_invariants(state: &SwapEngineState) -> Result<(), SwapInvariantViolation> {
    // 1. Check inventory invariants
    for (asset, inv) in &state.inventories {
        if inv.total_amount < BigDecimal::zero() {
            return Err(SwapInvariantViolation::ArithmeticSafetyViolated {
                reason: format!(
                    "Negative total inventory for asset {}: {}",
                    asset, inv.total_amount
                ),
            });
        }
        if inv.reserved_amount < BigDecimal::zero() {
            return Err(SwapInvariantViolation::ArithmeticSafetyViolated {
                reason: format!(
                    "Negative reserved inventory for asset {}: {}",
                    asset, inv.reserved_amount
                ),
            });
        }
        if inv.reserved_amount > inv.total_amount {
            return Err(SwapInvariantViolation::ReservationExceedsInventory {
                asset: asset.clone(),
                reserved: inv.reserved_amount.clone(),
                total: inv.total_amount.clone(),
                available: inv.available_amount(),
            });
        }
    }

    // 2. Track order reservations per asset to verify reservation conservation
    let mut order_reservations: HashMap<String, BigDecimal> = HashMap::new();

    for (order_id, order) in &state.orders {
        // Arithmetic bounds on order
        if order.requested_amount <= BigDecimal::zero() {
            return Err(SwapInvariantViolation::ArithmeticSafetyViolated {
                reason: format!(
                    "Non-positive requested amount for order {}: {}",
                    order_id, order.requested_amount
                ),
            });
        }
        if order.filled_amount < BigDecimal::zero() {
            return Err(SwapInvariantViolation::ArithmeticSafetyViolated {
                reason: format!(
                    "Negative filled amount for order {}: {}",
                    order_id, order.filled_amount
                ),
            });
        }
        if order.reserved_amount < BigDecimal::zero() {
            return Err(SwapInvariantViolation::ArithmeticSafetyViolated {
                reason: format!(
                    "Negative reserved amount for order {}: {}",
                    order_id, order.reserved_amount
                ),
            });
        }

        // Fills bounds
        if order.filled_amount > order.requested_amount {
            return Err(SwapInvariantViolation::FillsExceedOrderAmount {
                order_id: *order_id,
                filled: order.filled_amount.clone(),
                requested: order.requested_amount.clone(),
            });
        }

        // Fills sum matches order.filled_amount
        let fills_sum: BigDecimal = order.fills.iter().map(|f| f.amount_in.clone()).sum();
        if fills_sum != order.filled_amount {
            return Err(SwapInvariantViolation::ArithmeticSafetyViolated {
                reason: format!(
                    "Order {} fills sum {} does not match recorded filled_amount {}",
                    order_id, fills_sum, order.filled_amount
                ),
            });
        }

        // Validate each fill
        for fill in &order.fills {
            if fill.amount_in <= BigDecimal::zero()
                || fill.amount_out <= BigDecimal::zero()
                || fill.fee_paid < BigDecimal::zero()
            {
                return Err(SwapInvariantViolation::ValueConservationViolated {
                    order_id: *order_id,
                    input: fill.amount_in.clone(),
                    output: fill.amount_out.clone(),
                    fee: fill.fee_paid.clone(),
                    reason: "Non-positive fill input/output or negative fee".to_string(),
                });
            }
        }

        // Terminal order rules
        if order.status.is_terminal() {
            if order.reserved_amount > BigDecimal::zero() {
                return Err(SwapInvariantViolation::TerminalOrderTransition {
                    order_id: *order_id,
                    terminal_status: order.status,
                    attempted_action: format!(
                        "Terminal order {} has non-zero reservation {}",
                        order_id, order.reserved_amount
                    ),
                });
            }
        }

        // Status-specific value consistency
        match order.status {
            SwapOrderStatus::Filled => {
                if order.filled_amount != order.requested_amount {
                    return Err(SwapInvariantViolation::IllegalStateTransition {
                        order_id: *order_id,
                        from: SwapOrderStatus::PartiallyFilled,
                        to: SwapOrderStatus::Filled,
                    });
                }
            }
            SwapOrderStatus::PartiallyFilled => {
                if order.filled_amount == BigDecimal::zero()
                    || order.filled_amount == order.requested_amount
                {
                    return Err(SwapInvariantViolation::IllegalStateTransition {
                        order_id: *order_id,
                        from: SwapOrderStatus::Reserved,
                        to: SwapOrderStatus::PartiallyFilled,
                    });
                }
            }
            SwapOrderStatus::Pending => {
                if order.filled_amount > BigDecimal::zero() {
                    return Err(SwapInvariantViolation::IllegalStateTransition {
                        order_id: *order_id,
                        from: SwapOrderStatus::Pending,
                        to: SwapOrderStatus::PartiallyFilled,
                    });
                }
            }
            _ => {}
        }

        // Accumulate active reservations
        if !order.status.is_terminal() {
            let entry = order_reservations
                .entry(order.source_asset.clone())
                .or_insert_with(BigDecimal::zero);
            *entry = &*entry + &order.reserved_amount;
        }
    }

    // 3. Verify total active order reservations do not exceed inventory reservation
    for (asset, active_res) in order_reservations {
        if let Some(inv) = state.inventories.get(&asset) {
            if &active_res > &inv.reserved_amount {
                return Err(SwapInvariantViolation::ReservationExceedsInventory {
                    asset: asset.clone(),
                    reserved: active_res,
                    total: inv.reserved_amount.clone(),
                    available: inv.available_amount(),
                });
            }
        } else if active_res > BigDecimal::zero() {
            return Err(SwapInvariantViolation::ReservationExceedsInventory {
                asset: asset.clone(),
                reserved: active_res,
                total: BigDecimal::zero(),
                available: BigDecimal::zero(),
            });
        }
    }

    Ok(())
}
